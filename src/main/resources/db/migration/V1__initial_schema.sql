CREATE TABLE app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(64) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(16) NOT NULL CHECK (role IN ('USER','ADMIN'))
);
CREATE TABLE equipment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 description VARCHAR(1000) NOT NULL,
 total_quantity INTEGER NOT NULL CHECK (total_quantity >= 0),
 available_quantity INTEGER NOT NULL CHECK (available_quantity >= 0 AND available_quantity <= total_quantity)
);
CREATE TABLE reservation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES app_user(id),
 equipment_id BIGINT NOT NULL REFERENCES equipment(id),
 quantity INTEGER NOT NULL CHECK (quantity > 0),
 status VARCHAR(16) NOT NULL CHECK (status IN ('RESERVED','ISSUED','RETURNED','CANCELLED')),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_reservation_owner ON reservation(user_id,id);
CREATE INDEX idx_reservation_status ON reservation(status,id);
CREATE TABLE reservation_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reservation_id BIGINT NOT NULL REFERENCES reservation(id),
 actor VARCHAR(64) NOT NULL,
 from_status VARCHAR(16),
 to_status VARCHAR(16) NOT NULL,
 occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_event_reservation ON reservation_event(reservation_id,id);
